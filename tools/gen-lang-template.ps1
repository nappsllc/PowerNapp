<#
.SYNOPSIS
  Generates lang\en.txt (the template translators copy) from the built-in English in src\strings.h.
.DESCRIPTION
  Reads every X(ID, "key", L"English") entry of the STRINGS table, decodes the C escapes (\xHHHH, \n,
  \", \\) and writes "key = value" lines (UTF-8, no BOM, LF), escaping only \n and \\ as the loader
  expects. It also writes tests\sandbox\qps-ploc.txt, a pseudo-language for tests: accented English
  about 40% longer ("Start" becomes "[Start !]" in accented letters), placeholders and line breaks kept, @name = Pseudo,
  and tests\sandbox\qps-plocm.txt, the same strings as a right-to-left language (@rtl = 1, @name = Pseudo Mirrored).
  -Pseudo writes only the pseudo files. -Check writes nothing and exits 1 if either file on disk
  differs (used by CI).
#>
param([switch]$Check, [switch]$Pseudo)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$src = Join-Path $root 'src\strings.h'
$out = Join-Path $root 'lang\en.txt'
$pseudoOut = Join-Path $root 'tests\sandbox\qps-ploc.txt'
$mirrorOut = Join-Path $root 'tests\sandbox\qps-plocm.txt'

# a..z / A..Z -> accented look-alikes (code points: this script stays ASCII for Windows PowerShell 5.1)
$lower = 0x00E1,0x0180,0x00E7,0x010F,0x00E9,0x0192,0x011D,0x0125,0x00ED,0x0135,0x0137,0x013E,0x0271,
         0x00F1,0x00F3,0x00FE,0x02A0,0x0155,0x0161,0x0163,0x00FA,0x1E7D,0x0175,0x1E8B,0x00FD,0x017E
$upper = 0x00C1,0x0181,0x00C7,0x010E,0x00C9,0x0191,0x011C,0x0124,0x00CD,0x0134,0x0136,0x013D,0x1E40,
         0x00D1,0x00D3,0x00DE,0x01EA,0x0154,0x0160,0x0162,0x00DA,0x1E7C,0x0174,0x1E8A,0x00DD,0x017D
function Pseudo-Text([string]$s) {
    $sb = [System.Text.StringBuilder]::new('[')
    foreach ($part in [regex]::Split($s, '(%(?:ls|lld|d)|\n)')) {
        if ($part -match '^(%(ls|lld|d)|\n)$') { [void]$sb.Append($part); continue }  # placeholders, breaks
        foreach ($c in $part.ToCharArray()) {
            if ($c -cge 'a' -and $c -cle 'z') { [void]$sb.Append([char]$lower[[int]$c - 97]) }
            elseif ($c -cge 'A' -and $c -cle 'Z') { [void]$sb.Append([char]$upper[[int]$c - 65]) }
            else { [void]$sb.Append($c) }
        }
    }
    $pad = [math]::Ceiling($s.Length * 0.4)   # "[", " " and "]" count toward the 40%
    [void]$sb.Append(' ').Append('!' * [math]::Max(1, $pad - 3)).Append(']')
    $sb.ToString()
}

function Decode-C([string]$s) {
    $sb = [System.Text.StringBuilder]::new()
    for ($i = 0; $i -lt $s.Length; $i++) {
        $c = $s[$i]
        if ($c -ne '\') { [void]$sb.Append($c); continue }
        $i++
        $e = $s[$i]
        switch -CaseSensitive ($e) {
            'n' { [void]$sb.Append("`n") }
            't' { [void]$sb.Append("`t") }
            'x' {
                $j = $i + 1
                while ($j -lt $s.Length -and $s[$j] -match '[0-9A-Fa-f]') { $j++ }  # C: all hex digits
                if ($j -eq $i + 1) { throw "bad \x escape in: $s" }
                [void]$sb.Append([char][Convert]::ToInt32($s.Substring($i + 1, $j - $i - 1), 16))
                $i = $j - 1
            }
            default {
                if ($e -in '"', '\', "'") { [void]$sb.Append($e) } else { throw "unsupported escape \$e in: $s" }
            }
        }
    }
    $sb.ToString()
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('@name = English')
$lines.Add('# PowerNapp English template, generated from src\strings.h by tools\gen-lang-template.ps1: do not edit.')
$lines.Add('# To translate: copy to lang\<tag>.txt (e.g. de.txt), set @name to the language''s own name, add')
$lines.Add('# "@rtl = 1" for right-to-left scripts, and translate the values. Keep %ls / %d / %lld in the same')
$lines.Add('# order (a value whose placeholders differ is ignored). \n is a line break, \\ a backslash.')
$lines.Add('# A missing key falls back to English.')
$lines.Add('')
$rx = '^\s*X\(\s*(\w+)\s*,\s*"([^"]+)"\s*,\s*L"((?:[^"\\]|\\.)*)"\s*\)'
$seen = @{}
$plines = [System.Collections.Generic.List[string]]::new()
$plines.Add('@name = Pseudo')
$plines.Add('# Pseudo-language for tests (accented English, ~40% longer), generated by tools\gen-lang-template.ps1: do not edit.')
$plines.Add('')
$mlines = [System.Collections.Generic.List[string]]::new()
$mlines.Add('@name = Pseudo Mirrored')
$mlines.Add('@rtl = 1')
$mlines.Add('# Mirrored pseudo-language for tests (the Pseudo strings, laid out right to left), generated by tools\gen-lang-template.ps1: do not edit.')
$mlines.Add('')
foreach ($l in Get-Content -LiteralPath $src -Encoding UTF8) {
    $m = [regex]::Match($l, $rx)
    if (-not $m.Success) { continue }
    $key = $m.Groups[2].Value
    if ($seen.ContainsKey($key)) { throw "duplicate key $key" }
    $seen[$key] = 1
    $d = Decode-C $m.Groups[3].Value
    $lines.Add("$key = " + $d.Replace('\', '\\').Replace("`n", '\n'))
    $pv = "$key = " + (Pseudo-Text $d).Replace('\', '\\').Replace("`n", '\n')
    $plines.Add($pv)
    $mlines.Add($pv)
}
if ($seen.Count -eq 0) { throw "no STRINGS entries found in $src" }
$files = [ordered]@{}
if (-not $Pseudo -or $Check) { $files[$out] = ($lines -join "`n") + "`n" }
$files[$pseudoOut] = ($plines -join "`n") + "`n"
$files[$mirrorOut] = ($mlines -join "`n") + "`n"

if ($Check) {
    $bad = 0
    foreach ($f in $files.Keys) {
        $rel = $f.Substring($root.Length + 1)
        $disk = if (Test-Path -LiteralPath $f) { [System.IO.File]::ReadAllText($f) } else { '' }
        if ($disk.Replace("`r`n", "`n") -ne $files[$f]) { Write-Host "$rel is out of date: run tools\gen-lang-template.ps1"; $bad = 1 }
        else { Write-Host "$rel is up to date ($($seen.Count) keys)" }
    }
    exit $bad
}
foreach ($f in $files.Keys) {
    New-Item -ItemType Directory -Force -Path (Split-Path $f) | Out-Null
    [System.IO.File]::WriteAllText($f, $files[$f], [System.Text.UTF8Encoding]::new($false))
    Write-Host "wrote $($f.Substring($root.Length + 1)) ($($seen.Count) keys)"
}
